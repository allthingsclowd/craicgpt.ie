"""
content_pipeline/providers/litellm.py
======================================
LiteLLM-proxy provider for the daily content engine, plus the **local-first /
frontier-fallback** wrapper that underpins the whole open-source-first strategy.

TUTORIAL: base_url is the only thing that changes
-------------------------------------------------
Like ``lmstudio.py``, this is just ``ChatOpenAI`` with a custom ``base_url`` —
but pointed at the grazlab LiteLLM proxy instead of a single LM Studio box.
LiteLLM routes by model name across the whole fleet (M3 Ultra, DGX Spark, a
frontier provider), so the same chain code reaches any of them.

TUTORIAL: graceful degradation, made honest
-------------------------------------------
We *want* local open-source models to do the work — that's the point of the
project, and it's what the published "generated by …" note should usually say.
But a flaky local agentic run shouldn't produce a dud paper. ``run_with_fallback``
tries the local model, and only if it raises or fails a validation check does it
retry on a frontier model. Either way it returns a :class:`GenerationResult` that
records *which* model actually ran (so attribution is truthful) and *why* the
local one failed (so ``running-eval-loop`` can turn it into a regression case).
"""

from __future__ import annotations

import logging
import os
from dataclasses import dataclass
from typing import Any, Callable, Optional

from langchain_core.language_models import BaseChatModel

from content_pipeline.content_config import content_cfg

logger = logging.getLogger(__name__)


# ─────────────────────────────────────────────────────────────────────────────
# Per-route thinking policy
# ─────────────────────────────────────────────────────────────────────────────
# TUTORIAL: "thinking" is a per-ROUTE property, not a global switch
# ------------------------------------------------------------------
# Qwen3-family chat templates take ``chat_template_kwargs.enable_thinking``; vLLM's
# ``--reasoning-parser qwen3`` then returns the reasoning in a SEPARATE
# ``reasoning_content`` field, so ``.content`` (what we parse) stays clean and tool
# calls are still parsed by ``--tool-call-parser``. For most routes we turn thinking
# OFF — the Qwen3.6 lesson: the reasoning stream ate the token budget before any JSON
# appeared. One route is the exception, and it was MEASURED, not guessed:
#
#   2026-11-03, dgx/vllm/qwen3.8-flash-next-fp4 (nvidia/Qwen3.8-Flash-Next-FP4-Local),
#   structured JSON task:
#     thinking OFF               → mangled "CVE-2026-20002" into "CVE-20002" in 3/3 runs
#                                  (and earlier put a headline in the wrong JSON field)
#     thinking ON, effort "low"  → correct 3/3, at ~30 s a call instead of ~7 s and
#                                  ~900-1100 reasoning tokens
#
# Graham's call: keep Flash-Next, think at LOW effort on that route only. The extra
# reasoning needs its own room, so the output cap grows by THINKING_REASONING_TOKENS —
# otherwise the reasoning eats the answer's budget (the same failure, by another door).
# Override the route set with LLM_THINKING_MODELS (comma-separated; "" = none). Same
# design as thegeekwiththepeak.com's providers/litellm.py.
THINKING_REASONING_TOKENS = 2048
_DEFAULT_THINKING_MODELS = "dgx/vllm/qwen3.8-flash-next-fp4,dgx/vllm/qwen3.8-flash-next-fp4-long"

# A thinking call is ~4x slower (30 s vs 7 s measured), and its worst case is the full
# max_tokens + THINKING_REASONING_TOKENS at Flash-Next decode speed (~45 tok/s): the
# biggest caller (a 12000-token translation batch) is then ~14k tokens ≈ 310 s. The
# 180 s CONTENT_REQUEST_TIMEOUT default would cut that off and burn 3 retries on a call
# that was working, so a thinking route gets at least this per-call read timeout.
THINKING_MIN_TIMEOUT_S = 360.0


def thinking_models() -> frozenset[str]:
    """The routes that must think (``LLM_THINKING_MODELS``, read at call time)."""
    raw = os.environ.get("LLM_THINKING_MODELS", _DEFAULT_THINKING_MODELS)
    return frozenset(m.strip() for m in raw.split(",") if m.strip())


def thinking_policy(model: str, max_tokens: int) -> tuple[dict[str, Any], int]:
    """``(extra_body, max_tokens)`` for ``model``.

    On a route in :func:`thinking_models`: thinking ON at ``reasoning_effort: "low"``,
    with ``max_tokens`` widened by :data:`THINKING_REASONING_TOKENS` for the reasoning.
    Everywhere else: thinking OFF and ``max_tokens`` unchanged (the pre-2026-11-03
    behaviour of every caller that set it).
    """
    if model in thinking_models():
        return (
            {"chat_template_kwargs": {"enable_thinking": True}, "reasoning_effort": "low"},
            max_tokens + THINKING_REASONING_TOKENS,
        )
    return {"chat_template_kwargs": {"enable_thinking": False}}, max_tokens


def agentic_thinking_kwargs(model: str) -> dict[str, Any]:
    """``get_litellm_llm`` kwargs for an AGENT loop (research brain, rubric judge).

    Those callers never sent a thinking flag — they ran on each route's template
    default — so a non-thinking route gets ``{}`` and keeps exactly that behaviour.
    Only a thinking route is pinned to low effort (its template default would think
    at full effort, unbounded).
    """
    if model not in thinking_models():
        return {}
    extra_body, max_tokens = thinking_policy(model, content_cfg.max_tokens)
    return {"extra_body": extra_body, "max_tokens": max_tokens}


def request_timeout_for(model: str) -> float:
    """Per-call client timeout: the configured one, floored for a thinking route."""
    if model in thinking_models():
        return max(content_cfg.request_timeout, THINKING_MIN_TIMEOUT_S)
    return content_cfg.request_timeout


# ─────────────────────────────────────────────────────────────────────────────
# Result type
# ─────────────────────────────────────────────────────────────────────────────
@dataclass
class GenerationResult:
    """Outcome of a local-first generation attempt.

    Attributes:
        output:     The value returned by the (local or fallback) callable.
        model_used: The model route that actually produced ``output`` — this is
                    what gets stamped into the published attribution note.
        fell_back:  True if the local model failed and the fallback produced it.
        error:      The local failure reason (exception text or validation
                    message) when ``fell_back`` is True; otherwise None. Fed to
                    the eval feedback loop.
    """

    output: Any
    model_used: str
    fell_back: bool
    error: Optional[str] = None


# ─────────────────────────────────────────────────────────────────────────────
# Local-first → frontier-fallback wrapper
# ─────────────────────────────────────────────────────────────────────────────
def run_with_fallback(
    fn: Callable[[str], Any],
    *,
    local_model: str,
    fallback_model: str,
    validate: Optional[Callable[[Any], bool]] = None,
) -> GenerationResult:
    """Run ``fn(model)`` on the local model, falling back to a frontier model.

    Args:
        fn: A callable that takes a model route and returns generated output
            (e.g. a closure that invokes an LCEL chain with that model). It is
            called at most twice: once with ``local_model``, then — only on
            failure — once with ``fallback_model``.
        local_model: The preferred open-source route (tried first).
        fallback_model: The frontier route used only if the local attempt fails.
        validate: Optional predicate; output for which it returns False is
            treated as a failure and triggers fallback. Defaults to a truthiness
            check, so ``None``/``""``/empty results fall back.

    Returns:
        A :class:`GenerationResult`.

    Raises:
        The fallback's exception if BOTH the local and fallback attempts fail —
        we never return a silent dud.
    """
    check = validate if validate is not None else bool

    # ── Attempt 1: local open-source model ────────────────────────────────────
    local_error: Optional[str] = None
    try:
        output = fn(local_model)
        if check(output):
            logger.info("[fallback] local model %s succeeded", local_model)
            return GenerationResult(output=output, model_used=local_model, fell_back=False)
        local_error = f"validation failed for output from {local_model}"
        logger.warning("[fallback] %s", local_error)
    except Exception as exc:  # noqa: BLE001 — any local failure is a fallback trigger
        local_error = f"{type(exc).__name__}: {exc}"
        logger.warning("[fallback] local model %s raised: %s", local_model, local_error)

    # ── Attempt 2: cross-box fallback ─────────────────────────────────────────
    # NB: "fallback" here means the OTHER grazlab box, not a frontier provider —
    # the proxy has no frontier route. See content_config.fallback_text_model.
    logger.info("[fallback] retrying on fallback model %s", fallback_model)
    output = fn(fallback_model)  # if this raises, it propagates — no silent dud
    if not check(output):
        raise RuntimeError(
            f"fallback model {fallback_model} also produced invalid output "
            f"(local failure was: {local_error})"
        )
    return GenerationResult(
        output=output,
        model_used=fallback_model,
        fell_back=True,
        error=local_error,
    )


# ─────────────────────────────────────────────────────────────────────────────
# Provider factory
# ─────────────────────────────────────────────────────────────────────────────
def get_litellm_llm(
    model: str,
    *,
    temperature: Optional[float] = None,
    max_tokens: Optional[int] = None,
    extra_body: Optional[dict] = None,
) -> BaseChatModel:
    """Return a ChatOpenAI bound to the grazlab LiteLLM proxy for ``model``.

    Args:
        model: A route name from the grazlab catalog (e.g.
            ``m3/mlx/qwen3.8-27b-8bit``).
        temperature: Override the configured default.
        max_tokens: Override the configured default.
        extra_body: Extra request body fields forwarded to the proxy — e.g.
            ``{"chat_template_kwargs": {"enable_thinking": False}}`` to turn off
            the model's thinking preamble (which otherwise eats the token budget
            before any JSON is produced). Build it with :func:`thinking_policy`
            so a route that MUST think (Flash-Next) gets low-effort thinking.

    Returns:
        A ``ChatOpenAI`` instance. Construction does no network I/O — the
        endpoint is only contacted on ``.invoke()``.
    """
    # Imported lazily so importing this module (and the pure fallback logic) does
    # not require the heavy langchain_openai stack — keeps unit tests fast.
    from langchain_openai import ChatOpenAI

    logger.info(
        "[provider:litellm] model=%s base_url=%s",
        model,
        content_cfg.litellm_base_url,
    )
    kwargs: dict = {}
    if extra_body:
        kwargs["extra_body"] = extra_body
    return ChatOpenAI(
        model=model,
        base_url=content_cfg.litellm_base_url,
        api_key=content_cfg.litellm_api_key,
        temperature=content_cfg.temperature if temperature is None else temperature,
        max_tokens=content_cfg.max_tokens if max_tokens is None else max_tokens,
        # Floored for a thinking route — see THINKING_MIN_TIMEOUT_S.
        timeout=request_timeout_for(model),
        max_retries=2,
        **kwargs,
    )
